defmodule Covenant.MutateProtocolContractTest do
  use Covenant.Case, component: "covenant.mutate", async: true

  alias Covenant.Mutate.{Mutant, Mutator, Runner}

  @tag obligation: "covenant.mutate.I26"
  test "a shared implementation keeps all module identities without duplicate mutations" do
    source = "defimpl Sample.Protocol, for: [Map, List] do\n def value(_), do: 42\nend"
    assert {:ok, ast} = Mutator.parse(source, "shared.ex")
    modules = ["Sample.Protocol.Map", "Sample.Protocol.List"]
    sites = Mutator.sites(ast, modules: modules)
    assert length(sites) == 3
    assert Enum.all?(sites, &(Mutant.modules(&1) == modules))
    assert Runner.without_mutants(modules, sites) == []

    for site <- sites do
      assert {:ok, decoded} = site |> Mutant.to_map() |> Mutant.decode()
      assert Mutant.modules(decoded) == modules
    end
  end

  @tag obligation: "covenant.mutate.I26"
  test "either implementation owns a shared body when covers use different primitives" do
    modules = ["Sample.Protocol.Map", "Sample.Protocol.List"]
    source = "defimpl Sample.Protocol, for: [Map, List] do\n def value(_), do: 42\nend"
    {:ok, ast} = Mutator.parse(source, "shared.ex")
    [site | _] = Mutator.sites(ast, modules: modules)

    components =
      for {module, id} <- Enum.zip(modules, ["maps", "lists"]), into: %{} do
        covers = %Covenant.Covers{
          ref: {:function, module, "value", 1},
          text: "#{module}.value/1",
          file: "contract/#{id}/README.md",
          line: 1
        }

        {id,
         %Covenant.Contract.Component{
           id: id,
           app: "contract",
           name: id,
           form: :primitive,
           file: covers.file,
           covers: [covers]
         }}
      end

    contract = %Covenant.Contract{components: components}
    assert Covenant.Mutate.covered_by?(contract, "maps", site)
    assert Covenant.Mutate.covered_by?(contract, "lists", site)
  end

  @tag obligation: "covenant.mutate.I26"
  test "an exception for one module cannot exempt a shared body" do
    {:ok, contract} = Covenant.Contract.load(Covenant.ContractBuilder.fixture_contracts())
    component = Covenant.Contract.component(contract, "example.greeter")

    {:ok, ast} =
      Mutator.parse("defmodule Example.Greeter do\n def clamp(_), do: 42\nend", "shared.ex")

    [site | _] = Mutator.sites(ast)
    site = %{site | id: "m001", verdict: :survived, modules: ["Example.Greeter", "Other.Greeter"]}

    results = %{
      tests: [],
      mutants: [site],
      modules: site.modules,
      files: [site.file],
      baseline_ms: 0
    }

    matrix = Covenant.Mutate.Matrix.build(results, component: component)
    assert [%{sort: nil}] = matrix.survivors
    refute Covenant.Mutate.Matrix.ok?(matrix)
  end

  @tag obligation: "covenant.mutate.I26"
  test "protocol implementations are selected by their implementation module" do
    source = """
    defimpl Sample.Protocol, for: [Map, List] do
      def value(_input), do: 42
    end
    """

    assert {:ok, ast} = Mutator.parse(source, "protocol.ex")

    for type <- ["Map", "List"] do
      name = "Sample.Protocol.#{type}"
      sites = Mutator.sites(ast, modules: [name])
      assert length(sites) == 3
      assert Enum.all?(sites, &(&1.module == name and &1.function == "value/1"))
    end

    assert Mutator.sites(ast, modules: ["Sample.Protocol"]) == []
  end

  @tag obligation: "covenant.mutate.I26"
  test "an implementation can use its enclosing module as its type" do
    source = """
    defmodule Sample.Value do
      defstruct []
      defimpl Sample.Protocol do
        def value(_input), do: true
      end
    end
    """

    assert {:ok, ast} = Mutator.parse(source, "protocol.ex")
    sites = Mutator.sites(ast, modules: ["Sample.Protocol.Sample.Value"])
    assert Enum.any?(sites, &(&1.operator == :boolean_flip))
    assert Enum.all?(sites, &(&1.module == "Sample.Protocol.Sample.Value"))
    assert Mutator.sites(ast, modules: ["Sample.Value"]) == []
  end

  @tag obligation: ["covenant.mutate.I24", "covenant.mutate.I26"]
  test "implementations generated by a macro keep the provider's scope" do
    source = """
    defmodule Sample.Provider do
      defmacro build do
        quote do
          defimpl Sample.Protocol, for: Map do
            def value(_input), do: true
          end
        end
      end
    end
    """

    assert {:ok, ast} = Mutator.parse(source, "provider.ex")
    assert Mutator.sites(ast) == []
    sites = Mutator.sites(ast, macros: true, modules: ["Sample.Provider"])
    assert Enum.any?(sites, &(&1.operator == :boolean_flip))
    assert Enum.all?(sites, &(&1.module == "Sample.Provider" and &1.function == "build/0"))
  end
end

defmodule Covenant.MutateProtocolE2EContractTest do
  use Covenant.Case, component: "covenant.mutate", async: false

  @moduletag :e2e
  @moduletag timeout: 300_000
  @project Path.expand("../../../fixtures/mutate/vm_project", __DIR__)

  @tag obligation: "covenant.mutate.I26"
  test "workers load and restore mutated implementations through protocol dispatch" do
    mix = System.find_executable("mix") || raise "mix not on PATH"

    {output, status} =
      System.cmd(mix, ["covenant.mutate", "vm.protocol", "--jobs", "2"],
        cd: @project,
        env: [{"MIX_ENV", "test"}, {"COVENANT_RESULTS_DIR", nil}],
        stderr_to_stdout: true
      )

    assert status == 0, output

    matrix =
      @project
      |> Path.join("tmp/covenant/mutate/vm.protocol/kill_matrix.json")
      |> File.read!()
      |> JSON.decode!()

    assert matrix["summary"]["mutants"] == 3
    assert matrix["summary"]["killed"] == 3
    assert matrix["summary"]["survived"] == 0
    assert matrix["summary"]["invalid"] == 0
    assert Enum.all?(matrix["mutants"], &(&1["module"] == "Vm.ValueProtocol.Map"))
  end
end
